#!/usr/bin/env python3
"""Refresh or check local release metadata and the agent reading bundle."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import install_skill as installer

FULL_SOURCES = (
    "docs/en/usage.md", "INSTALL.md", "docs/en/harnesses.md",
    "docs/en/maintenance.md", "no-negative-echo/SKILL.md",
    *(f"no-negative-echo/references/{lang}/{module}.md"
      for lang in ("zh-CN", "en")
      for module in ("expression", "collaboration", "public-copy", "engineering")),
    "no-negative-echo/references/high-assurance-finalization.md", "LICENSE",
)


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def generated_files(root=ROOT):
    """Compute outputs without writing or accessing the network."""
    skill = root / "no-negative-echo"
    version = (root / "VERSION").read_text(encoding="utf-8").strip()
    result = {"no-negative-echo/LICENSE": (root / "LICENSE").read_text(encoding="utf-8")}
    delivery = json.loads((skill / "delivery.json").read_text(encoding="utf-8"))
    delivery["version"] = version
    delivery["files"] = sorted(p.as_posix() for p in installer.RUNTIME_FILES
                               if p not in {installer.PROVENANCE_FILE, Path("delivery.json")})
    result["no-negative-echo/delivery.json"] = json_text(delivery)
    marker = json.loads((skill / installer.PROVENANCE_FILE).read_text(encoding="utf-8"))
    marker["files"] = {}
    for relative in sorted(installer.RUNTIME_FILES - {installer.PROVENANCE_FILE}):
        key = "no-negative-echo/" + relative.as_posix()
        data = result[key].encode("utf-8") if key in result else (root / key).read_bytes()
        marker["files"][relative.as_posix()] = hashlib.sha256(data).hexdigest()
    marker_text = json_text(marker)
    result["no-negative-echo/" + installer.PROVENANCE_FILE.as_posix()] = marker_text
    digest = hashlib.sha256(marker_text.encode("utf-8")).hexdigest()
    script = (root / "scripts/install_skill.py").read_text(encoding="utf-8")
    result["scripts/install_skill.py"], count = re.subn(
        r'(CURRENT_PROVENANCE_SHA256 = \(\s*")[0-9a-f]{64}("\s*\))',
        lambda m: m[1] + digest + m[2], script)
    if count != 1:
        raise ValueError("Expected one installer provenance pin")
    for name in ("INSTALL.md", "README.md", "README_EN.md"):
        text = (root / name).read_text(encoding="utf-8")
        result[name], count = re.subn(
            r'(--expected-provenance-sha256\s+)[0-9a-f]{64}',
            lambda m: m[1] + digest, text)
        if not count:
            raise ValueError(f"Missing installation pin in {name}")
    sections = [f"# No Negative Echo — agent reading bundle\n\n"
                f"> Version {version}. Generated by scripts/build_release.py from repository sources.\n\n"
                "Use llms.txt as the short index. This file contains usage, installation, "
                "maintenance and the full bilingual rules for offline readers. Select the task's "
                "language and relevant rule sections. User intent and host permissions govern "
                "execution; reading documentation alone does not authorize installation or publication. "
                "Links are relative to the repository root.\n"]
    for name in FULL_SOURCES:
        text = result.get(name)
        if text is None:
            text = (root / name).read_text(encoding="utf-8")
        # Preserve root-relative navigation when concatenating nested documents.
        def link(match):
            target = match[1]
            if "://" in target or target.startswith("#"):
                return match[0]
            path, sep, anchor = target.partition("#")
            absolute = (root / Path(name).parent / path).resolve()
            relative = absolute.relative_to(root.resolve()).as_posix()
            return "](" + relative + (sep + anchor if sep else "") + ")"
        text = re.sub(r'\]\(([^)]+)\)', link, text)
        sections.append(f"\n---\n\n## Source: {name}\n\n{text.rstrip()}\n")
    result["llms-full.txt"] = "".join(sections)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="refresh generated files; default only checks")
    args = parser.parse_args()
    changed = []
    for name, text in generated_files().items():
        path = ROOT / name
        data = text.encode("utf-8")
        if not path.exists() or path.read_bytes() != data:
            changed.append(name)
            if args.write:
                path.write_bytes(data)
    if changed:
        print(("Updated: " if args.write else "Stale: ") + ", ".join(changed))
    else:
        print("Release metadata and agent bundle are current.")
    return 0 if args.write or not changed else 1


if __name__ == "__main__":
    raise SystemExit(main())
